"""GridSearchCV cho Logistic Regression/KNN; chọn cấu hình bằng validation."""

from __future__ import annotations

import argparse
from pathlib import Path

import joblib
import numpy as np
import pandas as pd
from sklearn.metrics import accuracy_score, confusion_matrix, f1_score, precision_score, recall_score, roc_auc_score
from sklearn.model_selection import GridSearchCV, StratifiedGroupKFold
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import StandardScaler
from sklearn.linear_model import LogisticRegression
from sklearn.neighbors import KNeighborsClassifier


PROJECT_ROOT = Path(__file__).resolve().parents[1]
TV2_OUTPUTS = PROJECT_ROOT / "NGUYENTHIANHHONG_2045240092_TV2" / "outputs"
FEATURE_DIR = PROJECT_ROOT / "TV3_VSCode" / "feature_cache"
MODEL_DIR = PROJECT_ROOT / "TV3_VSCode" / "models"
RESULTS_PATH = PROJECT_ROOT / "TV3_VSCode" / "results_tv3.csv"
CLASS_NAMES = ["Thấp (<10m)", "Trung bình (10–30m)", "Cao (30–60m)", "Rất cao (≥60m)"]
HEIGHT_COLUMN = "h_max"  # Đổi chỉ khi TV1/nhóm đã thống nhất h_mean hoặc h_p90.
THRESHOLDS = [10.0, 30.0, 60.0]  # Phải giống cấu hình đã chốt trong file TV2.
MIN_OPTICAL_VALID_FRAC = 0.5
FEATURE_SETS = {
    "hist": ["hist"],
    "hog": ["hog"],
    "glcm": ["glcm"],
    "edge": ["edge"],
    "hist_hog": ["hist", "hog"],
    "hog_glcm": ["hog", "glcm"],
    "hist_glcm_edge": ["hist", "glcm", "edge"],
    "all": ["hist", "hog", "glcm", "edge"],
}


def load_split(variant: str, split: str, stats: pd.DataFrame):
    cache_path = FEATURE_DIR / f"{variant}_{split}.npz"
    if not cache_path.exists():
        raise FileNotFoundError(f"Thiếu {cache_path}. Chạy tv3_extract_features.py trước.")
    # Existing TV3 feature caches may contain object-typed sample_id arrays;
    # these local NPZ files are generated by tv3_extract_features.py.
    data = np.load(cache_path, allow_pickle=True)
    if "optical_valid_frac" not in data.files:
        raise ValueError(
            f"{cache_path} chưa có thống kê tỷ lệ pixel ảnh hợp lệ. "
            "Chạy lại tv3_extract_features.py cho biến thể này."
        )
    valid_fractions = data["optical_valid_frac"]
    if np.any(valid_fractions < MIN_OPTICAL_VALID_FRAC):
        raise ValueError(
            f"{cache_path} có mẫu với <{MIN_OPTICAL_VALID_FRAC:.0%} pixel ảnh hợp lệ. "
            "Chạy lại tv3_extract_features.py để áp dụng bộ lọc thống nhất."
        )
    ids = data["sample_id"].astype(str)
    meta = stats.set_index("sample_id").reindex(ids)
    if meta[HEIGHT_COLUMN].isna().any():
        raise ValueError(f"Có sample_id không khớp hoặc thiếu {HEIGHT_COLUMN} trong stats.csv.")
    heights = meta[HEIGHT_COLUMN].astype(float).to_numpy()
    y = np.digitize(heights, THRESHOLDS).astype(np.int64)
    groups = meta["city_id"].astype(str).to_numpy()
    x_by_group = {name: data[name].astype(np.float32) for name in FEATURE_SETS["all"]}
    return ids, y, groups, x_by_group


def main() -> None:
    parser = argparse.ArgumentParser(description="Huấn luyện Logistic Regression và KNN")
    parser.add_argument("--variant", default="original", choices=("original", "contrast", "clahe", "denoise", "sharpen", "combo"))
    args = parser.parse_args()

    stats_path = TV2_OUTPUTS / "stats.csv"
    if not stats_path.exists():
        raise FileNotFoundError(f"Không thấy {stats_path}. Chạy file TV2 trước.")
    stats = pd.read_csv(stats_path)
    if HEIGHT_COLUMN not in stats.columns or "city_id" not in stats.columns:
        raise ValueError("stats.csv thiếu cột chiều cao/city_id cần cho nhãn và chia fold.")
    if "bld_frac" in stats.columns:
        empty_building_patches = int((stats["bld_frac"] == 0).sum())
        print(
            f"Theo quy tắc TV2, {empty_building_patches} patch không có pixel công trình "
            "có h_max=0 và được xếp vào lớp Thấp."
        )

    _, y_train, groups_train, x_train_groups = load_split(args.variant, "train", stats)
    _, y_val, _, x_val_groups = load_split(args.variant, "val", stats)
    MODEL_DIR.mkdir(parents=True, exist_ok=True)
    rows = []
    expected_labels = np.arange(4)

    for feature_name, group_names in FEATURE_SETS.items():
        X_train = np.concatenate([x_train_groups[name] for name in group_names], axis=1)
        X_val = np.concatenate([x_val_groups[name] for name in group_names], axis=1)
        for model_name in ("logistic", "knn"):
            if model_name == "logistic":
                estimator = LogisticRegression(max_iter=2000, class_weight="balanced", random_state=42)
                param_grid = {"model__C": [0.1, 1.0, 10.0]}
            else:
                estimator = KNeighborsClassifier(n_jobs=-1)
                param_grid = {
                    "model__n_neighbors": [3, 5, 7],
                    "model__weights": ["uniform", "distance"],
                    "model__p": [1, 2],
                }

            pipeline = Pipeline([("scale", StandardScaler()), ("model", estimator)])
            cv = StratifiedGroupKFold(n_splits=5, shuffle=True, random_state=42)
            search = GridSearchCV(
                pipeline, param_grid=param_grid, scoring="f1_macro", cv=cv,
                n_jobs=-1, refit=True, error_score="raise"
            )
            search.fit(X_train, y_train, groups=groups_train)
            prediction = search.best_estimator_.predict(X_val)
            result = {
                "variant": args.variant,
                "features": feature_name,
                "model": model_name,
                "best_params": str(search.best_params_),
                "cv_f1_macro": search.best_score_,
                "cv_f1_macro_mean": search.best_score_,
                "cv_f1_macro_std": search.cv_results_["std_test_score"][search.best_index_],
                "val_accuracy": accuracy_score(y_val, prediction),
                "val_precision_macro": precision_score(y_val, prediction, average="macro", zero_division=0),
                "val_recall_macro": recall_score(y_val, prediction, average="macro", zero_division=0),
                "val_f1_macro": f1_score(y_val, prediction, average="macro", zero_division=0),
                "val_confusion_matrix": str(confusion_matrix(y_val, prediction, labels=expected_labels).tolist()),
            }
            model_classes = getattr(search.best_estimator_, "classes_", np.array([]))
            if (
                hasattr(search.best_estimator_, "predict_proba")
                and len(np.unique(y_val)) == 4
                and np.array_equal(model_classes, expected_labels)
            ):
                result["val_roc_auc_ovr_macro"] = roc_auc_score(
                    y_val, search.best_estimator_.predict_proba(X_val), labels=expected_labels,
                    multi_class="ovr", average="macro"
                )
            else:
                result["val_roc_auc_ovr_macro"] = np.nan

            rows.append(result)
            model_path = MODEL_DIR / f"{args.variant}_{feature_name}_{model_name}.joblib"
            joblib.dump(search.best_estimator_, model_path)
            print(f"{feature_name:5s} | {model_name:8s} | val Macro-F1={result['val_f1_macro']:.3f} | {search.best_params_}")

    new_results = pd.DataFrame(rows)
    if RESULTS_PATH.exists():
        previous = pd.read_csv(RESULTS_PATH)
        keys = ["variant", "features", "model"]
        previous = previous[~previous[keys].apply(tuple, axis=1).isin(new_results[keys].apply(tuple, axis=1))]
        new_results = pd.concat([previous, new_results], ignore_index=True)
    new_results.to_csv(RESULTS_PATH, index=False, encoding="utf-8-sig")
    print(f"\nĐã lưu bảng kết quả: {RESULTS_PATH}")
    print("Thứ tự lớp:", dict(enumerate(CLASS_NAMES)))
    print("GridSearchCV tunes parameters with 5-fold city-grouped CV on train; validation metrics are reported separately; test is not evaluated here.")


if __name__ == "__main__":
    main()
